const fn transpose<const M: usize, const N: usize>(p: [[u8; N]; M]) -> [[u8; M]; N] {
    let mut q = [[0; M]; N];
    let mut i = 0;
    while i < M {
        let mut j = 0;
        while j < N {
            q[j][i] = p[i][j];
            j += 1;
        }
        i += 1;
    }
    q
}
